-- PostgreSQL rate-card schema. Run this before quotation_seed.postgresql.sql.
-- The seven rate-card tables and their columns mirror quotation_schema.sql.

CREATE TABLE IF NOT EXISTS quotation_rate_versions (
  version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_label VARCHAR(100) NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'active', 'archived')),
  notes TEXT,
  created_by VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_qrv_status ON quotation_rate_versions(status);

CREATE TABLE IF NOT EXISTS quotation_rate_audit_log (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  account VARCHAR(255) NOT NULL DEFAULT 'Unknown',
  action VARCHAR(50) NOT NULL,
  identifier VARCHAR(255) NOT NULL DEFAULT '',
  change_summary TEXT,
  data_payload JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_qral_identifier_timestamp
  ON quotation_rate_audit_log(identifier, event_timestamp DESC, audit_id DESC);

CREATE TABLE IF NOT EXISTS quotation_parameters (
  param_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id BIGINT NOT NULL REFERENCES quotation_rate_versions(version_id) ON DELETE CASCADE,
  param_key VARCHAR(100) NOT NULL,
  group_code VARCHAR(50) NOT NULL,
  label VARCHAR(150) NOT NULL,
  value_type VARCHAR(10) NOT NULL DEFAULT 'number'
    CHECK (value_type IN ('number', 'text', 'boolean')),
  value_number DECIMAL(20,8),
  value_text VARCHAR(255),
  unit VARCHAR(30),
  min_allowed DECIMAL(20,8),
  max_allowed DECIMAL(20,8),
  used_by VARCHAR(100),
  description VARCHAR(500),
  is_locked SMALLINT NOT NULL DEFAULT 0 CHECK (is_locked IN (0, 1)),
  sort_order INT NOT NULL DEFAULT 0,
  updated_by VARCHAR(255),
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_qp_version_key UNIQUE (version_id, param_key)
);
CREATE INDEX IF NOT EXISTS idx_qp_group ON quotation_parameters(version_id, group_code);

CREATE OR REPLACE FUNCTION quotation_parameters_touch_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS quotation_parameters_updated_at ON quotation_parameters;
CREATE TRIGGER quotation_parameters_updated_at
  BEFORE UPDATE ON quotation_parameters
  FOR EACH ROW EXECUTE FUNCTION quotation_parameters_touch_updated_at();

CREATE TABLE IF NOT EXISTS quotation_tier_sets (
  tier_set_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id BIGINT NOT NULL REFERENCES quotation_rate_versions(version_id) ON DELETE CASCADE,
  set_key VARCHAR(100) NOT NULL,
  label VARCHAR(150) NOT NULL,
  lookup_basis VARCHAR(50) NOT NULL,
  value1_label VARCHAR(50) NOT NULL DEFAULT 'value',
  value2_label VARCHAR(50),
  value3_label VARCHAR(50),
  below_min_behavior VARCHAR(10) NOT NULL DEFAULT 'first_row'
    CHECK (below_min_behavior IN ('first_row', 'zero')),
  used_by VARCHAR(100),
  description VARCHAR(500),
  CONSTRAINT uq_qts_version_key UNIQUE (version_id, set_key)
);

CREATE TABLE IF NOT EXISTS quotation_tier_rows (
  tier_row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tier_set_id BIGINT NOT NULL REFERENCES quotation_tier_sets(tier_set_id) ON DELETE CASCADE,
  range_min DECIMAL(18,6) NOT NULL,
  range_max DECIMAL(18,6),
  value1 DECIMAL(18,6) NOT NULL,
  value2 DECIMAL(18,6),
  value3 DECIMAL(18,6),
  CONSTRAINT uq_qtr_set_min UNIQUE (tier_set_id, range_min)
);

CREATE TABLE IF NOT EXISTS quotation_option_groups (
  group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id BIGINT NOT NULL REFERENCES quotation_rate_versions(version_id) ON DELETE CASCADE,
  group_key VARCHAR(50) NOT NULL,
  label VARCHAR(100) NOT NULL,
  attribute_schema JSONB NOT NULL,
  CONSTRAINT uq_qog_version_key UNIQUE (version_id, group_key)
);

CREATE TABLE IF NOT EXISTS quotation_options (
  option_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT NOT NULL REFERENCES quotation_option_groups(group_id) ON DELETE CASCADE,
  option_key VARCHAR(100) NOT NULL,
  label VARCHAR(150) NOT NULL,
  attributes JSONB NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  CONSTRAINT uq_qo_group_key UNIQUE (group_id, option_key)
);

CREATE TABLE IF NOT EXISTS quotation_cost_components (
  component_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id BIGINT NOT NULL REFERENCES quotation_rate_versions(version_id) ON DELETE CASCADE,
  code VARCHAR(10) NOT NULL,
  label VARCHAR(100) NOT NULL,
  report_group VARCHAR(50),
  toggle_field VARCHAR(50),
  handler VARCHAR(50) NOT NULL,
  formula_expression TEXT,
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  sort_order INT NOT NULL DEFAULT 0,
  CONSTRAINT uq_qcc_version_code UNIQUE (version_id, code)
);

-- Persist which active card produced the estimate and the server-side
-- calculation for each requested quantity.
ALTER TABLE quotation
  ADD COLUMN IF NOT EXISTS rate_version_id BIGINT;
ALTER TABLE quotation_item
  ALTER COLUMN paper_id DROP NOT NULL,
  ALTER COLUMN printing_id DROP NOT NULL,
  ALTER COLUMN handle_id DROP NOT NULL,
  ADD COLUMN IF NOT EXISTS rate_paper_option_key VARCHAR(100),
  ADD COLUMN IF NOT EXISTS rate_paper_option_label VARCHAR(150),
  ADD COLUMN IF NOT EXISTS rate_printing_option_key VARCHAR(100),
  ADD COLUMN IF NOT EXISTS rate_printing_option_label VARCHAR(150),
  ADD COLUMN IF NOT EXISTS rate_handle_option_key VARCHAR(100),
  ADD COLUMN IF NOT EXISTS rate_handle_option_label VARCHAR(150);
ALTER TABLE quotation_quantity
  ADD COLUMN IF NOT EXISTS estimated_unit_price NUMERIC(15,4),
  ADD COLUMN IF NOT EXISTS estimated_total_price NUMERIC(15,2),
  ADD COLUMN IF NOT EXISTS calculation_details JSONB;
